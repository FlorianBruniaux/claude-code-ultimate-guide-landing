export const CATALOG_READ_ON = '2026-09-30'

export type Mechanism = 'filter' | 'proxy' | 'mcp' | 'compaction' | 'memory' | 'index' | 'style' | 'routing' | 'delegation' | 'agent'

export const MECHANISM_LABELS: Record<Mechanism, { label: string; what: string }> = {
  filter: { label: 'Shell output filters', what: 'Rewrite or shorten command output before the agent reads it.' },
  proxy: { label: 'API proxies and context compression', what: 'Sit between the agent and the model API and shrink what is sent.' },
  mcp: { label: 'MCP tools and gateways', what: 'Replace or wrap tools so less raw output or schema enters the context.' },
  compaction: { label: 'Compaction and pruning', what: 'Summarize, drop or dedupe older context during a session.' },
  memory: { label: 'Memory', what: 'Store facts across sessions so the agent re-reads less.' },
  index: { label: 'Code index and search', what: 'Answer code questions from an index instead of reading whole files.' },
  style: { label: 'Output style', what: 'Instruct the model to write shorter answers or less code.' },
  routing: { label: 'Model routing', what: 'Send each request to a cheaper model when it is judged good enough.' },
  delegation: { label: 'Delegation', what: 'Hand heavy reads to another, cheaper model.' },
  agent: { label: 'Alternative agents', what: 'A different harness that claims to use fewer tokens than the usual ones.' },
}

