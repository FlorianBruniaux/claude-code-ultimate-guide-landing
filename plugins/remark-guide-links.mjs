/**
 * remark-guide-links.mjs
 *
 * Remark plugin that rewrites relative links in guide content for Starlight:
 *
 *   Pattern                           → Transformation
 *   ─────────────────────────────────────────────────────────────────────
 *   ./data-privacy.md                 → /guide/data-privacy/
 *   ./workflows/tdd-with-claude.md    → /guide/workflows/tdd-with-claude/
 *   ./ultimate-guide.md#4-agents      → /guide/ultimate-guide/04-agents/#4-agents (via anchor map)
 *   ./architecture.md#section         → /guide/architecture/#section
 *   ./images/foo.jpeg                 → /guide/images/foo.jpeg
 *   ../examples/agents/foo.md         → https://github.com/.../examples/agents/foo.md (fallback)
 *   ../CONTRIBUTING.md                → https://github.com/.../CONTRIBUTING.md (fallback)
 *   #section-anchor (same chapter)    → unchanged (same-page anchor)
 *   #section-anchor (cross-chapter)   → /guide/{chapter-slug}/#anchor (via anchor map)
 *   https://...                       → unchanged (external URL)
 *
 * NOTE: In Astro 5 with Content Layer API, this plugin is NOT reliably called
 * for content collection files (they are cached in the .astro data store).
 * Cross-chapter bare anchor rewriting is therefore handled by
 * scripts/prepare-guide-content.mjs → rewriteCrossChapterAnchors().
 * This plugin handles relative .md link rewriting at Vite build time.
 */

import { readFileSync, existsSync } from 'fs'
import { resolve, dirname, posix } from 'path'
import { fileURLToPath } from 'url'
import { visit } from 'unist-util-visit'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

const GITHUB_BASE = 'https://github.com/FlorianBruniaux/claude-code-ultimate-guide/blob/main/'
const GUIDE_BASE = '/guide/'

// Image extensions to handle as static files
const IMAGE_EXTS = new Set(['.jpeg', '.jpg', '.png', '.gif', '.svg', '.webp', '.avif'])

// Load anchor map (generated by prepare-guide-content.mjs)
function loadAnchorMap() {
  const anchorMapPath = resolve(ROOT, 'src/data/guide-anchor-map.json')
  try {
    const raw = readFileSync(anchorMapPath, 'utf-8')
    return JSON.parse(raw)
  } catch {
    return {}
  }
}

/**
 * Convert a guide-relative file path to a Starlight URL.
 * Returns null if the path should fall back to GitHub.
 *
 * @param {string} href - The raw href value (e.g., "./architecture.md")
 * @param {string|undefined} anchorFragment - URL fragment (e.g., "#section") or undefined
 * @param {object} anchorMap - Map of anchor → chapter slug
 * @returns {{ url: string, isExternal: boolean } | null}
 */
export function resolveGuideLink(href, anchorFragment, anchorMap, currentSourcePath) {
  // Normalize: strip leading ./
  const cleanHref = href.replace(/^\.\//, '')

  // ── Images ────────────────────────────────────────────────────────────
  // All guide images live in the single flat guide/images/ directory, served at
  // /guide/images/. Source files reference it as ./images/x (files directly in
  // guide/) or ../images/x, ../../images/x, etc. (files in a subdirectory like
  // guide/ecosystem/ or guide/core/). Strip everything up to and including the
  // last "images/" segment so both forms resolve to the same flat URL.
  const imageExt = IMAGE_EXTS.has('.' + cleanHref.split('.').pop()?.toLowerCase() || '')
  if (cleanHref.includes('images/') && imageExt) {
    return { url: '/guide/images/' + cleanHref.split('images/').pop(), isExternal: false }
  }
  if (imageExt) {
    return { url: '/guide/' + cleanHref.replace(/^(\.\.\/)+/, ''), isExternal: false }
  }

  const sourceDir = currentSourcePath ? posix.dirname(currentSourcePath) : 'guide'
  const repositoryPath = posix.normalize(posix.join(sourceDir, href.replace(/\\/g, '/')))

  if (repositoryPath === 'guide/core/claude-code-releases.md') {
    return { url: `/releases/${anchorFragment || ''}`, isExternal: false }
  }

  // ── Published directory indexes ────────────────────────────────────
  if (repositoryPath === 'guide/workflows' || repositoryPath === 'guide/workflows/') {
    return { url: `${GUIDE_BASE}workflows/${anchorFragment || ''}`, isExternal: false }
  }
  if (repositoryPath === 'guide/learning-path' || repositoryPath === 'guide/learning-path/') {
    return { url: `${GUIDE_BASE}learning-path/${anchorFragment || ''}`, isExternal: false }
  }

  // ── ultimate-guide.md (split into chapters) ────────────────────────
  if (repositoryPath === 'guide/ultimate-guide.md') {
    const anchor = anchorFragment?.replace('#', '') || ''
    if (anchor && anchorMap[anchor]) {
      return { url: `${GUIDE_BASE}${anchorMap[anchor]}/#${anchor}`, isExternal: false }
    }
    // No specific anchor or not found in map → link to ultimate guide index
    return { url: `${GUIDE_BASE}ultimate-guide/`, isExternal: false }
  }

  if (repositoryPath === 'guide/ultimate-guide.fr.md') {
    return { url: `${GUIDE_BASE}ultimate-guidefr/${anchorFragment || ''}`, isExternal: false }
  }

  if (repositoryPath === 'guide/README.md') {
    return { url: `${GUIDE_BASE}${anchorFragment || ''}`, isExternal: false }
  }

  if (repositoryPath === 'guide/workflows/README.md') {
    return { url: `${GUIDE_BASE}workflows/${anchorFragment || ''}`, isExternal: false }
  }

  if (repositoryPath === 'guide/learning-path/README.md') {
    return { url: `${GUIDE_BASE}learning-path/${anchorFragment || ''}`, isExternal: false }
  }

  const nestedMatch = repositoryPath.match(/^guide\/(workflows|learning-path)\/([^/]+)\.md$/)
  if (nestedMatch) {
    return {
      url: `${GUIDE_BASE}${nestedMatch[1]}/${nestedMatch[2]}/${anchorFragment || ''}`,
      isExternal: false,
    }
  }

  // ── Relative guide files in flattened source directories ───────────
  const KNOWN_GUIDE_SUBDIRS = new Set(['core', 'security', 'ecosystem', 'roles', 'ops'])
  const flattenedMatch = repositoryPath.match(/^guide\/([^/]+)\/([^/]+)\.md$/)
  if (flattenedMatch && KNOWN_GUIDE_SUBDIRS.has(flattenedMatch[1])) {
    const slug = flattenedMatch[2]
    const fragment = anchorFragment || ''
    return { url: `${GUIDE_BASE}${slug}/${fragment}`, isExternal: false }
  }

  const rootGuideMatch = repositoryPath.match(/^guide\/([^/]+)\.md$/)
  if (rootGuideMatch) {
    const slug = rootGuideMatch[1]
    const fragment = anchorFragment || ''
    return { url: `${GUIDE_BASE}${slug}/${fragment}`, isExternal: false }
  }

  const audienceMatch = repositoryPath.match(/^docs\/(for-(?:product-managers|tech-leads|cto|cio-ceo))\.md$/)
  if (audienceMatch) {
    return { url: `${GUIDE_BASE}${audienceMatch[1]}/${anchorFragment || ''}`, isExternal: false }
  }

  // ── Other repository Markdown files are source links, not site routes ──
  if (repositoryPath.endsWith('.md') && !repositoryPath.startsWith('../')) {
    return {
      url: `${GITHUB_BASE}${repositoryPath}${anchorFragment || ''}`,
      isExternal: true,
    }
  }

  // ── Absolute paths or other formats → unchanged ───────────────────
  return null
}

/**
 * Convert a guide-relative path to its GitHub URL (fallback for out-of-guide links).
 */
function toGitHubUrl(href) {
  // Strip leading ../
  const withoutDotDot = href.replace(/^(\.\.\/)+/, '')
  return GITHUB_BASE + withoutDotDot
}

/**
 * Extract the slug of the current file relative to the guide content dir.
 * e.g. "/path/to/content/docs/guide/ultimate-guide/00-introduction.md"
 *   → "ultimate-guide/00-introduction"
 */
function getCurrentSlug(filePath) {
  const match = filePath.match(/content\/docs\/guide\/(.+?)\.md/)
  return match ? match[1] : null
}

function getCurrentSourcePath(filePath) {
  const match = filePath.match(/content\/docs\/(guide\/.+?\.md)/)
  return match ? match[1] : null
}

/**
 * The remark plugin factory
 */
export function remarkGuideLinks() {
  const anchorMap = loadAnchorMap()

  return function transformer(tree, file) {
    // Only process files inside the guide content dir
    const filePath = file?.history?.[0] || ''
    if (!filePath.includes('content/docs/guide')) return
    const currentSourcePath = getCurrentSourcePath(filePath)

    visit(tree, ['link', 'image'], (node) => {
      const originalUrl = node.url || ''

      // Skip: external URLs
      if (originalUrl.startsWith('http://') || originalUrl.startsWith('https://')) return
      // Handle: bare anchors (#section)
      if (originalUrl.startsWith('#')) {
        const anchor = originalUrl.slice(1)
        const currentSlug = getCurrentSlug(filePath)
        const targetSlug = anchorMap[anchor]

        // Cross-chapter anchor → rewrite to the correct chapter URL
        if (targetSlug && currentSlug && targetSlug !== currentSlug) {
          node.url = `${GUIDE_BASE}${targetSlug}/#${anchor}`
        }
        // Same chapter or unknown anchor → leave as-is (same-page anchor)
        return
      }
      // Skip: data: URIs
      if (originalUrl.startsWith('data:')) return
      // Skip: absolute paths
      if (originalUrl.startsWith('/')) return

      // Split URL from fragment
      const hashIdx = originalUrl.indexOf('#')
      const hrefPart = hashIdx >= 0 ? originalUrl.slice(0, hashIdx) : originalUrl
      const fragmentPart = hashIdx >= 0 ? originalUrl.slice(hashIdx) : ''

      if (!hrefPart) return // pure anchor, skip

      const resolved = resolveGuideLink(hrefPart, fragmentPart, anchorMap, currentSourcePath)

      if (resolved) {
        node.url = resolved.url
      } else if (hrefPart.startsWith('../') || hrefPart.startsWith('..\\')) {
        // Fall back to GitHub for out-of-guide references
        node.url = toGitHubUrl(hrefPart) + fragmentPart
      }
      // Otherwise: leave unchanged (unknown relative path)
    })
  }
}

export default remarkGuideLinks
